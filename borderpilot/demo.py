"""Sandbox demo run that produces the competition's execution evidence.

    python -m borderpilot.demo

Writes to evidence/:
  sandbox.db            the SQLite sandbox bank after the run (accounts, payments, approvals, audit chain)
  operation_log.jsonl   the full hash-chained audit log (one JSON object per line, with prev_hash/hash)
  payments.json         executed sandbox payments
  DEMO_TRANSCRIPT.md    a human-readable account of every scenario
Timestamps are real (UTC). Money is simulated; nothing leaves the sandbox."""
from __future__ import annotations

import json
from pathlib import Path

from .app import build_app, new_student_session
from .drills import _FakeClient, _tool
from .fx import DATA_DIR
from .money import fmt
from .policy import PolicyDenied

ROOT = Path(__file__).resolve().parent.parent
EVID = ROOT / "evidence"
TIER = {"READ": "read-only", "PROPOSE": "propose", "EXECUTE": "move money", "UNKNOWN": "unknown"}


def _inv(name: str) -> str:
    return (DATA_DIR / "invoices" / name).read_text()


class Transcript:
    def __init__(self):
        self.lines: list[str] = []

    def h(self, t):
        self.lines += ["", f"## {t}", ""]

    def p(self, t=""):
        self.lines.append(t)

    def steps(self, s, start=0):
        for t in s.trace[start:]:
            mark = "ok" if t.get("ok") else f"DENIED `{t.get('code')}`"
            self.p(f"{t['step']}. `{t['tool']}` ({TIER.get(t['tier'], t['tier'])}, by {t['actor']}): {mark} - "
                   f"{t.get('summary', '')}")
        self.p()

    def state(self, st):
        v = st.get("verification")
        if v:
            reasons = "; ".join(f"{r['code']} (+{r['points']})" for r in v["reasons"]) or "none"
            self.p(f"- Payee check: **{v['status']}**, risk {v['risk_score']}/100. Reasons: {reasons}.")
        c = st.get("comparison")
        if c:
            self.p(f"- Routes: " + "; ".join(f"{o['name']} {o['total']['text']} "
                                              f"({'in time' if o['deadline_ok'] else 'late'})" for o in c["options"]))
            self.p(f"- Recommendation: {c['rationale']}")
        if st.get("plan"):
            pl = st["plan"]
            self.p(f"- Plan fingerprint (SHA-256): `{pl['plan_hash']}`")
            self.p(f"- Slip: pay {pl['beneficiary']['name']} ({pl['beneficiary']['account']}) "
                   f"{pl['dst_amount']['text']}; student pays {pl['src_total']['text']} via {pl['route_name']}; "
                   f"arrives by {pl['arrives_by']}, due {pl['due_date']}.")
        self.p(f"- Final status: **{st['status']}**. {st['message'].splitlines()[0] if st['message'] else ''}")


def main():
    EVID.mkdir(exist_ok=True)
    db = EVID / "sandbox.db"
    if db.exists():
        db.unlink()
    app = build_app(db_path=str(db))
    T = Transcript()
    T.p("# BorderPilot - sandbox execution evidence")
    T.p()
    T.p("Generated by `python -m borderpilot.demo`. All money is simulated in a local SQLite sandbox bank. "
        "Institutions, students and accounts are fictional. FX rates and fees are illustrative samples. "
        "Every step below also appears in `operation_log.jsonl`, a SHA-256 hash chain that can be re-verified.")

    def student(n):
        return new_student_session(app, user_id=f"student-{n:03d}")

    # A. genuine UK tuition -> paid; keep the token to replay it later
    T.h("A. Genuine UK tuition invoice: proposed, approved by the student, paid")
    sa = student(1)
    st = app.run(sa, sa.add_document(_inv("01_harbourview_legit.txt")))
    T.steps(sa)
    token_a = app.approvals.issue(plan_hash=sa.plan.hash(), user_id=sa.user_id)
    app.ledger.audit("user", "approval_granted", {"user": sa.user_id, "plan_hash": sa.plan.hash(), "step_up": False})
    n = len(sa.trace)
    app.call_tool(sa, "execute_payment", {"approval_token": token_a}, actor="user")
    T.steps(sa, n)
    T.state(app.state(sa))

    # B. "bank details changed" fraud
    T.h("B. Fraud: 'our bank details have changed' - blocked before any plan exists")
    sb = student(2)
    st = app.run(sb, sb.add_document(_inv("02_harbourview_account_swapped.txt")))
    T.steps(sb)
    T.state(st)

    # C. prompt injection
    T.h("C. Prompt injection inside the invoice - instructions ignored, payment blocked")
    sc = student(3)
    st = app.run(sc, sc.add_document(_inv("05_prompt_injection.txt")))
    T.steps(sc)
    T.state(st)
    T.p(f"- Extracted account stayed the official one: `{sc.invoice.public()['account_masked']}`; the injected "
        "account was never used.")

    # D. look-alike sender -> needs step-up
    T.h("D. Look-alike sender domain - approval without step-up refused, then approved after out-of-band check")
    sd = student(4)
    st = app.run(sd, sd.add_document(_inv("03_lookalike_domain_urgent.txt")))
    T.steps(sd)
    n = len(sd.trace)
    try:
        app.approve(sd, sd.plan.hash(), step_up=False)
    except PolicyDenied as e:
        T.p(f"Plain approval refused: `{e.code}` - {e.message}.")
    app.approve(sd, sd.plan.hash(), step_up=True)
    T.steps(sd, n)
    T.state(app.state(sd))
    T.p("- The money went to the institution's official account (the look-alike email could not change it).")

    # E. China tuition in CNY
    T.h("E. Genuine tuition in China (CNY) - paid")
    se = student(5)
    st = app.run(se, se.add_document(_inv("06_southbay_cny_legit.txt")))
    app.approve(se, se.plan.hash())
    T.steps(se)
    T.state(app.state(se))

    # F. LLM tool-use loop (scripted model turns stand in for Claude offline)
    T.h("F. LLM planner loop (scripted model turns; the same loop calls Claude when an API key is configured)")
    sf = student(6)
    doc = sf.add_document(_inv("07_rheinland_legit.txt"))
    client = _FakeClient([[_tool("read_invoice", 1, doc_id=doc)], [_tool("verify_payee", 2)],
                          [_tool("get_fx_quote", 3)], [_tool("compare_routes", 4)], [_tool("forecast_budget", 5)],
                          [_tool("propose_payment", 6)],
                          [{"type": "text", "text": "Your payment slip is ready. Please review and approve it."}]])
    st = app.run_llm(sf, doc, client, "scripted-model")
    app.approve(sf, sf.plan.hash())
    T.steps(sf)
    T.state(app.state(sf))

    # G. hijacked model tries to pay by itself
    T.h("G. Hijacked model tries to execute a payment itself - denied by the allow-list")
    sg = student(7)
    doc = sg.add_document(_inv("01_harbourview_legit.txt"))
    client = _FakeClient([[_tool("read_invoice", 1, doc_id=doc)],
                          [_tool("execute_payment", 2, approval_token="i-approve-myself")],
                          [{"type": "text", "text": "Paid."}]])
    app.run_llm(sg, doc, client, "hijacked-model")
    T.steps(sg)
    T.p(f"- Balance unchanged: {fmt(app.ledger.balance(sg.funding_account_id), 'PLN')}.")

    # H. replay of A's approval
    T.h("H. Replay: student A's used approval token submitted again")
    n = len(sa.trace)
    try:
        app.call_tool(sa, "execute_payment", {"approval_token": token_a}, actor="user")
    except PolicyDenied as e:
        T.p(f"Replay refused: `{e.code}` - {e.message}.")
    T.steps(sa, n)

    ok, bad = app.ledger.verify_audit()
    rows = app.ledger.audit_rows()
    with open(EVID / "operation_log.jsonl", "w") as f:
        for r in rows:
            f.write(json.dumps({**r, "payload": json.loads(r["payload"])}, ensure_ascii=False) + "\n")
    pays = [{k: v for k, v in p.items() if k != "beneficiary_account"} for p in app.ledger.payments()]
    (EVID / "payments.json").write_text(json.dumps(pays, indent=2))
    T.h("Integrity check")
    T.p(f"- Audit entries: {len(rows)}. Hash chain re-verified from genesis: **{'INTACT' if ok else f'BROKEN at {bad}'}**.")
    T.p(f"- Executed sandbox payments: {len(pays)}; blocked or refused attempts are recorded as `tool_denied:*` "
        "entries.")
    T.p(f"- Last chain hash: `{rows[-1]['hash']}`")
    (EVID / "DEMO_TRANSCRIPT.md").write_text("\n".join(T.lines) + "\n")
    app.ledger.close()
    print(f"audit entries={len(rows)} chain_ok={ok} payments={len(pays)}")
    print("written: evidence/DEMO_TRANSCRIPT.md, evidence/operation_log.jsonl, evidence/payments.json, evidence/sandbox.db")


if __name__ == "__main__":
    main()
